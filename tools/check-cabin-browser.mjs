/** Actual UI input and original model; no mocked cabin/door state. */
export async function checkCabin({ page, check, screenshot, state, seek, pause }) {
  await page.setViewport({ width:1440, height:900, deviceScaleFactor:1 });
  await seek(page,1);
  let s=(await state(page)).cabin;
  check('Both real doors are rigged and initially closed',s.available && s.door.panels===14 && s.door.amount===0,s);
  await page.click('[data-action="doors"]');
  await page.waitForFunction(()=>window.__REVUELTO__.getState().cabin.door.amount===1,{timeout:30000});
  s=(await state(page)).cabin;
  check('Door button lifts both scissor doors',s.door.leftAngle>1 && s.door.rightAngle>1);
  check('Both door skins, glass, lining and mirrors move',s.door.triangles.left===2265 && s.door.triangles.right===2265);
  await screenshot(page,'cabin-doors-open');
  await page.click('[data-action="doors"]');
  await page.waitForFunction(()=>window.__REVUELTO__.getState().cabin.door.amount===0,{timeout:30000});
  check('Closing returns doors exactly to their rest position',(await state(page)).cabin.door.amount===0);
  await page.click('[data-action="interior"]');
  check('Entry locks page scroll and starts camera transition',await page.evaluate(()=>document.documentElement.classList.contains('cabin-locked')) && (await state(page)).cabin.mode==='entering');
  await pause(2100);await screenshot(page,'cabin-entering');
  await page.waitForFunction(()=>window.__REVUELTO__.getState().cabin.mode==='inside',{timeout:45000});
  s=(await state(page)).cabin;
  check('Camera arrives at the actual driver eye position',Math.abs(s.cameraPosition[0]-.445)<.001 && Math.abs(s.cameraPosition[1]-1.045)<.001 && Math.abs(s.cameraPosition[2]+.075)<.001,s);
  check('Interior uses a close near plane and natural first-person field of view',s.near===.008 && s.fov===70);
  check('Outside assembly controls are inert in first person',await page.$eval('[data-reveal-controls]',el=>el.inert));
  await screenshot(page,'cabin-driver');
  await page.focus('canvas');await page.keyboard.press('ArrowRight');
  await page.waitForFunction(()=>window.__REVUELTO__.getState().cabin.yaw<-.09,{timeout:30000});
  check('Arrow keys rotate the seated view',(await state(page)).cabin.yaw<-.09);
  const eye=(await state(page)).cabin.cameraPosition;
  await page.mouse.move(850,440);await page.mouse.down();await page.mouse.move(980,490,{steps:8});await page.mouse.up();
  await page.waitForFunction(()=>window.__REVUELTO__.getState().cabin.yaw>.1,{timeout:30000});
  check('Mouse drag changes head direction without moving the driver',JSON.stringify((await state(page)).cabin.cameraPosition)===JSON.stringify(eye) && (await state(page)).cabin.yaw>.1);
  await page.click('[data-action="cabin-passenger"]');
  await page.waitForFunction(()=>{const c=window.__REVUELTO__.getState().cabin;return c.lookSettled&&c.yaw===-1.35;},{timeout:30000});
  check('Passenger preset looks across the actual cabin',(await state(page)).cabin.yaw<-1.2);
  await screenshot(page,'cabin-passenger');
  await page.click('[data-action="cabin-left"]');
  await page.waitForFunction(()=>{const c=window.__REVUELTO__.getState().cabin;return c.lookSettled&&c.yaw===1.35;},{timeout:30000});
  check('Left door preset settles at the opposite side of the cabin',(await state(page)).cabin.yaw===1.35);
  await page.click('[data-action="cabin-front"]');
  await page.waitForFunction(()=>{const c=window.__REVUELTO__.getState().cabin;return c.lookSettled&&c.yaw===0;},{timeout:30000});
  check('Dashboard preset returns to the forward view',(await state(page)).cabin.pitch===-.24);
  await page.click('[data-action="cabin-doors"]');
  await page.waitForFunction(()=>window.__REVUELTO__.getState().cabin.door.amount===0,{timeout:30000});
  check('Doors can be closed from the driver seat',(await state(page)).cabin.mode==='inside');
  await screenshot(page,'cabin-driver-closed');
  await page.setViewport({width:390,height:844,deviceScaleFactor:1});
  await page.waitForFunction(()=>{const s=window.__REVUELTO__.getState();return s.cabin.mode==='inside'&&s.cabin.fov===78&&s.active;},{timeout:30000});
  check('Mobile keeps the camera inside the cabin',(await state(page)).cabin.mode==='inside' && (await state(page)).cabin.fov===78);
  check('Interior controls fit mobile screen',await page.$eval('.cabin-presets',el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.bottom<=innerHeight}));
  await screenshot(page,'cabin-mobile');
  check('Mobile rotation preserves the driver position',JSON.stringify((await state(page)).cabin.cameraPosition)===JSON.stringify(eye));
  await page.setViewport({width:844,height:390,deviceScaleFactor:1});
  await page.waitForFunction(()=>{const s=window.__REVUELTO__.getState();return s.cabin.mode==='inside'&&s.cabin.fov===70&&s.active;},{timeout:30000});
  check('Landscape rotation keeps the interior camera and overlay active',await page.$eval('.stage',el=>{const r=el.getBoundingClientRect();return Math.abs(r.top)<1&&Math.abs(r.height-innerHeight)<1}));
  await screenshot(page,'cabin-landscape');
  await page.setViewport({width:390,height:844,deviceScaleFactor:1});
  await page.waitForFunction(()=>window.__REVUELTO__.getState().cabin.fov===78,{timeout:30000});
  await page.focus('canvas');await page.keyboard.press('Tab');
  check('Keyboard focus remains in the interior controls',await page.evaluate(()=>document.querySelector('[data-cabin-overlay]').contains(document.activeElement)));
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>window.__REVUELTO__.getState().cabin.mode==='exterior',{timeout:45000});
  check('Escape opens doors and returns to the exterior',(await state(page)).cabin.door.amount===1);
  check('Exiting releases scrolling and restores launch focus',await page.evaluate(()=>!document.documentElement.classList.contains('cabin-locked')&&document.activeElement?.dataset.action==='interior'));
  check('Rotated exit restores the assembled reveal in the viewport',await page.evaluate(()=>{const s=window.__REVUELTO__.getState(),r=document.querySelector('.stage').getBoundingClientRect();return s.progress>=.965&&s.visibleParts===s.parts&&r.top>=-1&&r.bottom<=innerHeight+1;}));
  await page.setViewport({width:1440,height:900,deviceScaleFactor:1});await seek(page,1);
  await page.click('[data-action="interior"]');await pause(500);await page.keyboard.press('Escape');
  await page.waitForFunction(()=>window.__REVUELTO__.getState().cabin.mode==='exterior',{timeout:30000});
  check('Entry can be cancelled safely with Escape',await page.evaluate(()=>!document.documentElement.classList.contains('cabin-locked')));
  await page.click('[data-action="doors"]');await pause(200);
  await seek(page,0);
  check('Replay resets doors and cabin before disassembling',(await state(page)).cabin.door.amount===0&&(await state(page)).visibleParts===0);
}
